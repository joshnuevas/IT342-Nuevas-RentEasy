do $$
begin
  if exists (
    select 1
    from information_schema.columns
    where table_schema = 'public'
      and table_name = 'rental_orders'
      and column_name = 'shipping_name'
  ) then
    update public.rental_orders
    set
      delivery_name = coalesce(delivery_name, shipping_name),
      delivery_email = coalesce(delivery_email, shipping_email),
      delivery_phone = coalesce(delivery_phone, shipping_phone),
      delivery_address = coalesce(delivery_address, shipping_address),
      delivery_city = coalesce(delivery_city, shipping_city),
      delivery_zip = coalesce(delivery_zip, shipping_zip);
  end if;
end $$;


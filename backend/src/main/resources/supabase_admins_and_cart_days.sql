create table if not exists public.rental_order_items (
  order_item_id bigint generated by default as identity primary key,
  order_id bigint not null references public.rental_orders(order_id) on delete cascade,
  product_id bigint references public.products(product_id) on delete set null,
  product_name varchar(255),
  price numeric(12, 2),
  days integer not null default 1
);
